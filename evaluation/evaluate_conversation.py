def result_matches(actual, expected):

    if isinstance(expected, dict):

        if not isinstance(actual, dict):
            return False

        for key, expected_value in expected.items():

            if key not in actual:
                return False

            actual_value = actual[key]

            if isinstance(expected_value, float):

                if not isinstance(actual_value, (int, float)):
                    return False

                if abs(actual_value - expected_value) > 0.1:
                    return False

            elif isinstance(expected_value, str):

                if not isinstance(actual_value, str):
                    return False

                if actual_value.strip().lower() != expected_value.strip().lower():
                    return False

            else:

                if actual_value != expected_value:
                    return False

        return True

    if isinstance(expected, (int, float)):

        if not isinstance(actual, (int, float)):
            return False

        return abs(actual - expected) <= 0.1

    return actual == expected


def answer_matches(answer, expected_phrases):

    answer_lower = answer.lower().replace(",", "")

    return all(
        phrase.lower().replace(",", "") in answer_lower
        for phrase in expected_phrases
    )


def arguments_match(actual, expected):
    """
    Compare tool arguments while treating string values
    case-insensitively and ignoring surrounding whitespace.
    """

    if not isinstance(actual, dict):
        return False

    if not isinstance(expected, dict):
        return False

    if set(actual.keys()) != set(expected.keys()):
        return False

    for key in expected:

        if key not in actual:
            return False

        actual_value = actual[key]
        expected_value = expected[key]

        if isinstance(actual_value, str) and isinstance(expected_value, str):

            if actual_value.strip().lower() != expected_value.strip().lower():
                return False

        else:

            if actual_value != expected_value:
                return False

    return True


def execute_tool(df, tool_name, arguments):

    function_to_call = AVAILABLE_TOOLS.get(tool_name)

    if function_to_call is None:

        return {
            "success": False,
            "error": f"Unknown tool: {tool_name}",
        }

    try:

        return function_to_call(
            df,
            **arguments,
        )

    except Exception as e:

        return {
            "success": False,
            "error": str(e),
        }


def run_single_test(df, test):

    conversation = []

    question = test["question"]

    conversation.append(
        {
            "role": "user",
            "content": question,
        }
    )

    response = chat(
        model=MODEL,
        messages=[
            {
                "role": "system",
                "content": SYSTEM_PROMPT,
            }
        ] + conversation,
        tools=TOOLS,
        options={
            "temperature": 0,
        },
    )

    if not response.message.tool_calls:

        return {
            "tool": False,
            "arguments": False,
            "result": False,
            "answer": False,
        }

    tool_call = response.message.tool_calls[0]

    actual_tool = tool_call.function.name
    actual_arguments = tool_call.function.arguments or {}

    tool_ok = actual_tool == test["expected_tool"]

    arguments_ok = arguments_match(
        actual_arguments,
        test["expected_arguments"],
    )

    result = execute_tool(
        df,
        actual_tool,
        actual_arguments,
    )

    result_ok = result_matches(
        result,
        test["expected_result"],
    )

    conversation.append(response.message)

    conversation.append(
        {
            "role": "tool",
            "content": json.dumps(result),
        }
    )

    final_prompt = (
        "Answer the user's question using ONLY the tool result below. "
        "Do not invent or change any values. "
        "Be concise and directly answer the question.\n\n"
        f"User question: {question}\n"
        f"Tool result: {json.dumps(result)}\n\n"
        "If the tool result contains success=False, clearly state "
        "that the requested item was not found and mention the exact "
        "item requested.\n"
        "If the tool result contains a percentage, state the exact "
        "percentage and what product or region it refers to."
    )

    final_response = chat(
        model=MODEL,
        messages=[
            {
                "role": "system",
                "content": SYSTEM_PROMPT,
            },
            {
                "role": "user",
                "content": final_prompt,
            },
        ],
        options={
            "temperature": 0,
        },
    )

    answer = final_response.message.content or ""

    answer_ok = answer_matches(
        answer,
        test["expected_answer"],
    )

    return {
        "tool": tool_ok,
        "arguments": arguments_ok,
        "result": result_ok,
        "answer": answer_ok,
        "actual_tool": actual_tool,
        "actual_arguments": actual_arguments,
        "result_data": result,
        "answer_text": answer,
    }


def run_context_test(df, test):

    conversation = []

    tool_passes = 0
    argument_passes = 0

    for index, question in enumerate(test["questions"]):

        conversation.append(
            {
                "role": "user",
                "content": question,
            }
        )

        response = chat(
            model=MODEL,
            messages=[
                {
                    "role": "system",
                    "content": SYSTEM_PROMPT,
                }
            ] + conversation,
            tools=TOOLS,
            options={
                "temperature": 0,
            },
        )

        if not response.message.tool_calls:
            continue

        tool_call = response.message.tool_calls[0]

        actual_tool = tool_call.function.name
        actual_arguments = tool_call.function.arguments or {}

        expected_tool = test["expected_tools"][index]
        expected_arguments = test["expected_arguments"][index]

        if actual_tool == expected_tool:
            tool_passes += 1

        if arguments_match(
            actual_arguments,
            expected_arguments,
        ):
            argument_passes += 1

        result = execute_tool(
            df,
            actual_tool,
            actual_arguments,
        )

        conversation.append(response.message)

        conversation.append(
            {
                "role": "tool",
                "content": json.dumps(result),
            }
        )

        final_response = chat(
            model=MODEL,
            messages=[
                {
                    "role": "system",
                    "content": SYSTEM_PROMPT,
                }
            ] + conversation,
            options={
                "temperature": 0,
            },
        )

        conversation.append(
            {
                "role": "assistant",
                "content": final_response.message.content or "",
            }
        )

    return {
        "tool_passes": tool_passes,
        "argument_passes": argument_passes,
        "total": len(test["questions"]),
    }


def run_evaluation():

    df = load_data()

    tool_passes = 0
    argument_passes = 0
    result_passes = 0
    answer_passes = 0

    total = len(TEST_CASES)

    print("=" * 60)
    print("          InsightAgent Evaluation")
    print("=" * 60)

    for test in TEST_CASES:

        print("\n" + "-" * 60)
        print("Test:", test["id"])
        print("Question:", test["question"])

        result = run_single_test(
            df,
            test,
        )

        if result["tool"]:

            tool_passes += 1
            print("✅ Tool selection: PASS")

        else:

            print("❌ Tool selection: FAIL")

        if result["arguments"]:

            argument_passes += 1
            print("✅ Arguments: PASS")

        else:

            print("❌ Arguments: FAIL")

            if "actual_arguments" in result:

                print(
                    "Expected:",
                    test["expected_arguments"],
                )

                print(
                    "Actual:",
                    result["actual_arguments"],
                )

        if result["result"]:

            result_passes += 1
            print("✅ Tool result: PASS")

        else:

            print("❌ Tool result: FAIL")

            if "result_data" in result:

                print(
                    "Expected:",
                    test["expected_result"],
                )

                print(
                    "Actual:",
                    result["result_data"],
                )

        if result["answer"]:

            answer_passes += 1
            print("✅ Final answer: PASS")

        else:

            print("❌ Final answer: FAIL")

            if "answer_text" in result:

                print(
                    "Actual answer:",
                    result["answer_text"],
                )

    print("\n")
    print("=" * 60)
    print("       Contextual Conversation Evaluation")
    print("=" * 60)

    context_tool_passes = 0
    context_argument_passes = 0
    context_total = 0

    for test in CONTEXT_TESTS:

        context_result = run_context_test(
            df,
            test,
        )

        context_tool_passes += context_result["tool_passes"]
        context_argument_passes += context_result["argument_passes"]
        context_total += context_result["total"]

    tool_score = (
        tool_passes / total
    ) * 100

    argument_score = (
        argument_passes / total
    ) * 100

    result_score = (
        result_passes / total
    ) * 100

    answer_score = (
        answer_passes / total
    ) * 100

    context_tool_score = (
        context_tool_passes / context_total
    ) * 100

    context_argument_score = (
        context_argument_passes / context_total
    ) * 100

    overall_score = (
        tool_score
        + argument_score
        + result_score
        + answer_score
        + context_tool_score
        + context_argument_score
    ) / 6

    print("\n")
    print("=" * 60)
    print("             FINAL RESULTS")
    print("=" * 60)

    print(
        f"Tool Selection:       "
        f"{tool_passes}/{total} "
        f"({tool_score:.1f}%)"
    )

    print(
        f"Arguments:            "
        f"{argument_passes}/{total} "
        f"({argument_score:.1f}%)"
    )

    print(
        f"Tool Results:         "
        f"{result_passes}/{total} "
        f"({result_score:.1f}%)"
    )

    print(
        f"Final Answers:        "
        f"{answer_passes}/{total} "
        f"({answer_score:.1f}%)"
    )

    print("-" * 60)

    print(
        f"Context Tool Selection:"
        f" {context_tool_passes}/{context_total} "
        f"({context_tool_score:.1f}%)"
    )

    print(
        f"Context Arguments:    "
        f"{context_argument_passes}/{context_total} "
        f"({context_argument_score:.1f}%)"
    )

    print("-" * 60)

    print(
        f"Overall Agent Score:  "
        f"{overall_score:.1f}%"
    )

    print("=" * 60)


