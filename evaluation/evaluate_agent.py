# ============================================================
# RESULT COMPARISON
# ============================================================

def result_matches(actual, expected):

    if isinstance(expected, dict):

        if not isinstance(actual, dict):
            return False

        for key, expected_value in expected.items():

            if key not in actual:
                return False

            actual_value = actual[key]

            if isinstance(expected_value, float):

                if not isinstance(actual_value, (int, float)):
                    return False

                if abs(actual_value - expected_value) > 0.1:
                    return False

            else:

                if actual_value != expected_value:
                    return False

        return True

    if isinstance(expected, (int, float)):

        if not isinstance(actual, (int, float)):
            return False

        return abs(actual - expected) <= 0.1

    return actual == expected


# ============================================================
# ANSWER VALIDATION
# ============================================================

def answer_matches(answer, expected_phrases):

    if not answer:
        return False

    normalized = (
        answer
        .lower()
        .replace(",", "")
        .replace("$", "")
    )

    return all(
        phrase.lower().replace(",", "").replace("$", "")
        in normalized
        for phrase in expected_phrases
    )


# ============================================================
# TOOL EXECUTION
# ============================================================

def execute_tool(df, tool_name, arguments):

    function_to_call = AVAILABLE_TOOLS.get(tool_name)

    if function_to_call is None:

        return {
            "success": False,
            "error": f"Unknown tool: {tool_name}",
        }

    try:

        return function_to_call(
            df,
            **arguments,
        )

    except Exception as e:

        return {
            "success": False,
            "error": str(e),
        }


# ============================================================
# DETERMINISTIC FINAL ANSWER
# ============================================================

def generate_final_answer(tool_name, result, question):

    """
    Generate the final response deterministically.

    IMPORTANT:
    We intentionally DO NOT call the LLM here.

    The tool result has already been verified, so using another
    small LLM call introduces unnecessary variability.
    """

    # --------------------------------------------------------
    # Unknown product
    # --------------------------------------------------------

    if isinstance(result, dict):

        if result.get("success") is False:

            if result.get("error_type") == "UNKNOWN_PRODUCT":

                # Extract product from the original question.
                words = question.strip().rstrip("?").split()

                product = None

                for i, word in enumerate(words):

                    cleaned = word.strip(".,!?")

                    if cleaned.lower() in {
                        "tesla",
                        "apple",
                    }:

                        product = cleaned
                        break

                if product is None:
                    product = "requested product"

                return (
                    f"{product} was not found in the product data."
                )

            return result.get(
                "message",
                "The requested information was not found."
            )

    # --------------------------------------------------------
    # Product revenue
    # --------------------------------------------------------

    if tool_name == "get_product_revenue":

        product = result.get("product")
        revenue = result.get("revenue")

        return (
            f"{product} generated "
            f"${revenue:,.0f} in revenue."
        )

    # --------------------------------------------------------
    # Best product
    # --------------------------------------------------------

    if tool_name == "get_best_product":

        product = result.get("product")
        revenue = result.get("revenue")

        return (
            f"{product} was the top-performing product "
            f"with ${revenue:,.0f} in revenue."
        )

    # --------------------------------------------------------
    # Best region
    # --------------------------------------------------------

    if tool_name == "get_best_region":

        region = result.get("region")
        revenue = result.get("revenue")

        return (
            f"{region} was the best-performing region "
            f"with ${revenue:,.0f} in revenue."
        )

    # --------------------------------------------------------
    # Total quantity
    # --------------------------------------------------------

    if tool_name == "get_total_quantity":

        return (
            f"We sold {result:,.0f} units altogether."
        )

    # --------------------------------------------------------
    # Total revenue
    # --------------------------------------------------------

    if tool_name == "get_total_revenue":

        return (
            f"Total revenue was ${result:,.0f}."
        )

    # --------------------------------------------------------
    # Revenue difference
    # --------------------------------------------------------

    if tool_name == "get_revenue_difference":

        first = result.get("first_product")
        second = result.get("second_product")
        difference = result.get("difference")

        return (
            f"{first} made ${difference:,.0f} more "
            f"than {second}."
        )

    # --------------------------------------------------------
    # Percentage
    # --------------------------------------------------------

    if tool_name == "get_percentage_of_total":

        value = result.get("filter_value")
        percentage = result.get("percentage")

        return (
            f"{value} contributed "
            f"{percentage:.1f}% of total revenue."
        )

    # --------------------------------------------------------
    # Specific region
    # --------------------------------------------------------

    if tool_name == "get_revenue_by_region":

        if len(result) == 1:

            region, revenue = next(
                iter(result.items())
            )

            return (
                f"{region} generated "
                f"${revenue:,.0f} in revenue."
            )

        return json.dumps(result)

    # --------------------------------------------------------
    # Revenue by product
    # --------------------------------------------------------

    if tool_name == "get_revenue_by_product":

        ordered = sorted(
            result.items(),
            key=lambda item: item[0],
        )

        lines = [
            f"{product}: ${revenue:,.0f}"
            for product, revenue in ordered
        ]

        return "Revenue by product:\n" + "\n".join(lines)

    # --------------------------------------------------------
    # Fallback
    # --------------------------------------------------------

    return str(result)


# ============================================================
# SINGLE TEST
# ============================================================

def run_single_test(df, test):

    question = test["question"]

    response = chat(
        model=MODEL,
        messages=[
            {
                "role": "system",
                "content": SYSTEM_PROMPT,
            },
            {
                "role": "user",
                "content": question,
            },
        ],
        tools=TOOLS,
        options={
            "temperature": 0,
            "num_ctx": 2048,
            "num_predict": 128,
        },
    )

    # --------------------------------------------------------
    # No tool call
    # --------------------------------------------------------

    if not response.message.tool_calls:

        return {
            "tool": False,
            "arguments": False,
            "result": False,
            "answer": False,
            "actual_tool": None,
            "actual_arguments": None,
            "result_data": None,
            "answer_text": "",
        }

    # --------------------------------------------------------
    # Tool call
    # --------------------------------------------------------

    tool_call = response.message.tool_calls[0]

    actual_tool = tool_call.function.name

    actual_arguments = dict(
        tool_call.function.arguments
    )

    # --------------------------------------------------------
    # Tool validation
    # --------------------------------------------------------

    tool_ok = (
        actual_tool
        == test["expected_tool"]
    )

    arguments_ok = (
        actual_arguments
        == test["expected_arguments"]
    )

    # --------------------------------------------------------
    # Execute tool
    # --------------------------------------------------------

    result = execute_tool(
        df,
        actual_tool,
        actual_arguments,
    )

    # --------------------------------------------------------
    # Validate tool result
    # --------------------------------------------------------

    result_ok = result_matches(
        result,
        test["expected_result"],
    )

    # --------------------------------------------------------
    # Generate final answer WITHOUT LLM
    # --------------------------------------------------------

    answer = generate_final_answer(
        actual_tool,
        result,
        question,
    )

    # --------------------------------------------------------
    # Validate final answer
    # --------------------------------------------------------

    answer_ok = answer_matches(
        answer,
        test["expected_answer"],
    )

    return {
        "tool": tool_ok,
        "arguments": arguments_ok,
        "result": result_ok,
        "answer": answer_ok,
        "actual_tool": actual_tool,
        "actual_arguments": actual_arguments,
        "result_data": result,
        "answer_text": answer,
    }


# ============================================================
# PRINT STATUS
# ============================================================

def print_status(passed, label):

    if passed:
        print(
            f"✅ {label}: PASS"
        )

    else:
        print(
            f"❌ {label}: FAIL"
        )


# ============================================================
# MAIN EVALUATION
# ============================================================

def run_evaluation():

    df = load_data()

    tool_passes = 0
    argument_passes = 0
    result_passes = 0
    answer_passes = 0

    total = len(TEST_CASES)

    print("=" * 60)
    print("          KUDOO AGENT EVALUATION")
    print("=" * 60)

    for test in TEST_CASES:

        print(
            "\n"
            + "-"
            * 60
        )

        print(
            "Test:",
            test["id"]
        )

        print(
            "Question:",
            test["question"]
        )

        result = run_single_test(
            df,
            test,
        )

        # ----------------------------------------------------
        # Tool selection
        # ----------------------------------------------------

        if result["tool"]:

            tool_passes += 1

            print_status(
                True,
                "Tool selection",
            )

        else:

            print_status(
                False,
                "Tool selection",
            )

            print(
                "Expected:",
                test["expected_tool"],
            )

            print(
                "Actual:",
                result["actual_tool"],
            )

        # ----------------------------------------------------
        # Arguments
        # ----------------------------------------------------

        if result["arguments"]:

            argument_passes += 1

            print_status(
                True,
                "Arguments",
            )

        else:

            print_status(
                False,
                "Arguments",
            )

            print(
                "Expected:",
                test["expected_arguments"],
            )

            print(
                "Actual:",
                result["actual_arguments"],
            )

        # ----------------------------------------------------
        # Tool result
        # ----------------------------------------------------

        if result["result"]:

            result_passes += 1

            print_status(
                True,
                "Tool result",
            )

        else:

            print_status(
                False,
                "Tool result",
            )

            print(
                "Expected:",
                test["expected_result"],
            )

            print(
                "Actual:",
                result["result_data"],
            )

        # ----------------------------------------------------
        # Final answer
        # ----------------------------------------------------

        if result["answer"]:

            answer_passes += 1

            print_status(
                True,
                "Final answer",
            )

        else:

            print_status(
                False,
                "Final answer",
            )

            print(
                "Actual answer:",
                result["answer_text"],
            )

    # ========================================================
    # SCORES
    # ========================================================

    tool_score = (
        tool_passes / total
    ) * 100

    argument_score = (
        argument_passes / total
    ) * 100

    result_score = (
        result_passes / total
    ) * 100

    answer_score = (
        answer_passes / total
    ) * 100

    overall_score = (
        tool_score
        + argument_score
        + result_score
        + answer_score
    ) / 4

    # ========================================================
    # FINAL REPORT
    # ========================================================

    print("\n")

    print("=" * 60)
    print("             KUDOO EVALUATION RESULTS")
    print("=" * 60)

    print(
        f"Tool Selection: "
        f"{tool_passes}/{total} "
        f"({tool_score:.1f}%)"
    )

    print(
        f"Arguments:      "
        f"{argument_passes}/{total} "
        f"({argument_score:.1f}%)"
    )

    print(
        f"Tool Results:   "
        f"{result_passes}/{total} "
        f"({result_score:.1f}%)"
    )

    print(
        f"Final Answers:  "
        f"{answer_passes}/{total} "
        f"({answer_score:.1f}%)"
    )

    print("-" * 60)

    print(
        f"Overall Agent Score: "
        f"{overall_score:.1f}%"
    )

    print("=" * 60)


if __name__ == "__main__":
    run_evaluation()